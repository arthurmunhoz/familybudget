export type WKey = keyof (typeof S)['pt']
export function wt(lang: Lang, key: WKey, vars: Record<string, string | number> = {}): string {
  let s: string = S[lang][key] ?? S.en[key]
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}
